async def clear_annotations(auth_data: dict = Depends(AUTH_CORPUS_WRITE)) -> JSONResponse:
    """Remove all annotation files for the corpus from the Sparv server.

    This action cannot be performed while a job is running.

    ### Example

    ```bash
    curl -X DELETE '{{host}}/corpus/annotations/remove/<resource_id>' -H 'Authorization: Bearer YOUR_JWT'
    ```
    """
    resource_id = auth_data["resource_id"]
    # Check if there is an active job
    job = processing.require_job(registry.get(resource_id).job)
    if job.status.is_running():
        raise exceptions.MinkHTTPException(
            return_code=return_codes.PROCESS_RUNNING, info="Cannot clear annotations while a job is running"
        )

    try:
        sparv_output = job.clean()
        return utils.response(
            return_code=return_codes.REMOVED_CONTENT, info="Removed annotations", sparv_output=sparv_output
        )
    except Exception as e:
        raise exceptions.MinkHTTPException(
            return_code=return_codes.FAILED_REMOVING_CONTENT, info=f"Failed to remove annotations: {e}"
        ) from e


