async def abort_job(auth_data: dict = Depends(AUTH_CORPUS_WRITE)) -> JSONResponse:
    """Abort the currently running job for the corpus.

    If the job is in the queue but not yet running, it will be removed from the queue. If the job is running, it will be
    stopped.

    ### Example

    ```bash
    curl -X POST '{{host}}/corpus/job/abort/<resource_id>' -H 'Authorization: Bearer YOUR_JWT'
    ```
    """
    info_item = registry.get(auth_data["resource_id"])
    job = processing.abort_job(info_item)
    return utils.response(return_code=return_codes.ABORTED_JOB, job_status=job.status.serialize())


